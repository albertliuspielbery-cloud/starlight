NUMW = {1: '一', 2: '兩', 3: '三', 4: '四', 5: '五', 6: '六', 7: '七', 8: '八'}
DIRS = {'右': (1, 0), '左': (-1, 0), '上': (0, -1), '下': (0, 1)}

def grid_tasks(mid, M):
    P = {tuple(map(int, k.split(','))): v for k, v in M['places'].items()}
    sx, sy = M['start']; sn = M['startName']; W, H = M['w'], M['h']
    inside = lambda x, y: 0 <= x < W and 0 <= y < H
    easy, mid_, hard = [], [], []
    # easy：從入口往一個方向走 n 格，走到哪裡？
    for d, (dx, dy) in DIRS.items():
        for n in range(1, 5):
            x, y = sx + dx * n, sy + dy * n
            if not inside(x, y): break
            # 路上經過的格子不能有別的地點（不然孩子會以為停在那裡）
            if any((sx + dx * k, sy + dy * k) in P for k in range(1, n)): break
            if (x, y) in P:
                easy.append(dict(t='go', moves=[[d, n]], ans=P[(x, y)][2], line=f'從{sn}往{d}走{NUMW[n]}格，會走到哪裡？'))
    # mid：從入口走到某個地點，要往哪一邊、走幾格？（同一排或同一列，路上沒有別的地點）
    for (x, y), v in P.items():
        for d, (dx, dy) in DIRS.items():
            for n in range(1, 6):
                if (sx + dx * n, sy + dy * n) == (x, y) and not any((sx + dx * k, sy + dy * k) in P for k in range(1, n)):
                    mid_.append(dict(t='count', to=v[2], dir=d, ans=n, line=f'從{sn}走到{v[2]}那裡，要往{d}走幾格？'))
                    mid_.append(dict(t='dir', to=v[2], ans=d, line=f'{v[2]}在{sn}的哪一邊？'))
    # hard：先往一個方向走，再轉彎走，會走到哪裡？（第一段終點不能是地點、路上不經過其他地點）
    for d1, (ax, ay) in DIRS.items():
        for n1 in range(1, 5):
            x1, y1 = sx + ax * n1, sy + ay * n1
            if not inside(x1, y1): break
            if (x1, y1) in P or any((sx + ax * k, sy + ay * k) in P for k in range(1, n1)): break
            for d2, (bx, by) in DIRS.items():
                if (bx, by) in [(ax, ay), (-ax, -ay)]: continue
                for n2 in range(1, 5):
                    x2, y2 = x1 + bx * n2, y1 + by * n2
                    if not inside(x2, y2): break
                    if any((x1 + bx * k, y1 + by * k) in P for k in range(1, n2)): break
                    if (x2, y2) in P:
                        hard.append(dict(t='go', moves=[[d1, n1], [d2, n2]], ans=P[(x2, y2)][2],
                                         line=f'從{sn}往{d1}走{NUMW[n1]}格，再往{d2}走{NUMW[n2]}格，會走到哪裡？'))
                        break
    # 帶路：孩子點箭頭，一格一格走到指定地點（任何一條路都算對；走到了再問「你走了幾格？」只在最短路時問）
    lead = [dict(t='lead', to=v[2], line=f'請你帶路，走到{v[2]}那裡！', shortest=abs(x - sx) + abs(y - sy)) for (x, y), v in P.items()]
    return dict(easy=easy, mid=mid_, hard=hard, lead=lead)

