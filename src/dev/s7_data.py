# ---------------------------------------------------------------- 拆段故事（照 story19 的自動規則先算好，給寫程式和 QA 對照）
SENT = re.compile(r'[^。！？!?]+[。！？!?」』）)～…]*')
def sents(t):
    return [x.strip() for x in SENT.findall(str(t or '')) if x.strip()]
DEP = re.compile(r'(換上|穿上|打扮|捲起袖子|拿好|帶好|帶著|牽好|準備好了嗎|出發|我們去.{0,8}囉)')

def story_plan(D, boy=False, NL=10):
    ver = D['story_b'] if boy else D['story_p']
    T = D['story'][:]; T.insert(D['storyAt'], ver)
    N = len(T); r = dict(hook='', hookWhole=False, segs=[], dep=None)
    ss = sents(T[0])
    nh = 2 if len(ss) > 1 and len(re.sub(r'[^\w]', '', ss[0])) < 5 else 1
    rest = []
    if len(ss) <= nh: r['hook'] = T[0]; r['hookWhole'] = True
    else:
        r['hook'] = ''.join(ss[:nh]); rest.append(''.join(ss[nh:]))
    for i in range(1, N):
        if i == N - 1 and N >= 3 and DEP.search(T[i]): r['dep'] = T[i]; continue
        rest.append(T[i])
    G = max(1, NL - 1)
    j = 0
    while j < len(rest) and len(rest) < G:   # 每一句都有錄音（TSV 一句一個），頁數不夠時拆成一句一頁
        q = sents(rest[j])
        if len(q) < 2: j += 1; continue
        take = min(len(q), G - len(rest) + 1)
        grp = [''.join(q[round(k * len(q) / take):round((k + 1) * len(q) / take)]) for k in range(take)]
        rest[j:j + 1] = grp; j += len(grp)
    R = len(rest)
    if not R: return r
    nseg = min(R, G); base = R // nseg; extra = R % nseg; k0 = 0
    for s in range(nseg):
        n = base + (1 if extra > 0 else 0)
        if extra > 0: extra -= 1
        n = min(n, 2)
        if s == nseg - 1: n = R - k0
        at = 1 if nseg == 1 else 1 + round(s * (G - 1) / (nseg - 1))
        r['segs'].append({'at': at, 'pages': rest[k0:k0 + n]}); k0 += n
    return r

